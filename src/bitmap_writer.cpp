// ============================================================
// Construction
// ============================================================

BitmapWriter::BitmapWriter(int width, int height)
    : width_(std::max(1, width)), height_(std::max(1, height)),
      pixels_(static_cast<size_t>(width_) * height_ * 3, 0)
{
}

// ============================================================
// Pixel operations
// ============================================================

void BitmapWriter::setPixel(int x, int y, uint8_t r, uint8_t g, uint8_t b)
{
    if (x < 0 || x >= width_ || y < 0 || y >= height_) return;
    size_t idx = (static_cast<size_t>(y) * width_ + x) * 3;
    pixels_[idx]     = r;
    pixels_[idx + 1] = g;
    pixels_[idx + 2] = b;
}

void BitmapWriter::fillBackground(uint8_t r, uint8_t g, uint8_t b)
{
    for (size_t i = 0; i < pixels_.size(); i += 3) {
        pixels_[i]     = r;
        pixels_[i + 1] = g;
        pixels_[i + 2] = b;
    }
}

// ============================================================
// Drawing primitives
// ============================================================

void BitmapWriter::drawHorizontalLine(int x1, int x2, int y,
                                      uint8_t r, uint8_t g, uint8_t b)
{
    if (y < 0 || y >= height_) return;
    if (x1 > x2) std::swap(x1, x2);
    x1 = std::max(x1, 0);
    x2 = std::min(x2, width_ - 1);
    for (int x = x1; x <= x2; ++x) {
        size_t idx = (static_cast<size_t>(y) * width_ + x) * 3;
        pixels_[idx]     = r;
        pixels_[idx + 1] = g;
        pixels_[idx + 2] = b;
    }
}

void BitmapWriter::drawLine(int x1, int y1, int x2, int y2,
                            uint8_t r, uint8_t g, uint8_t b)
{
    // Bresenham's line algorithm
    int dx = std::abs(x2 - x1);
    int dy = -std::abs(y2 - y1);
    int sx = (x1 < x2) ? 1 : -1;
    int sy = (y1 < y2) ? 1 : -1;
    int err = dx + dy;

    while (true) {
        setPixel(x1, y1, r, g, b);
        if (x1 == x2 && y1 == y2) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x1 += sx; }
        if (e2 <= dx) { err += dx; y1 += sy; }
    }
}

void BitmapWriter::drawThickLine(int x1, int y1, int x2, int y2, int thickness,
                                 uint8_t r, uint8_t g, uint8_t b)
{
    // Draw a line with given pixel thickness by drawing the base line
    // plus offset lines perpendicular to the direction
    drawLine(x1, y1, x2, y2, r, g, b);
    int half = thickness / 2;
    if (half < 1) return;
    
    // For nearly horizontal lines, offset vertically; for nearly vertical, offset horizontally
    int dx = std::abs(x2 - x1);
    int dy = std::abs(y2 - y1);
    
    for (int offset = 1; offset <= half; ++offset) {
        if (dx >= dy) {
            // Offset vertically
            drawLine(x1, y1 - offset, x2, y2 - offset, r, g, b);
            drawLine(x1, y1 + offset, x2, y2 + offset, r, g, b);
        } else {
            // Offset horizontally
            drawLine(x1 - offset, y1, x2 - offset, y2, r, g, b);
            drawLine(x1 + offset, y1, x2 + offset, y2, r, g, b);
        }
    }
}

void BitmapWriter::drawCircle(int cx, int cy, int radius,
                              uint8_t r, uint8_t g, uint8_t b, bool filled)
{
    if (radius <= 0) { setPixel(cx, cy, r, g, b); return; }

    // Midpoint circle algorithm
    int x = 0, y = radius;
    int d = 1 - radius;

    auto plotSymmetric = [&](int px, int py) {
        if (filled) {
            drawHorizontalLine(cx - px, cx + px, cy + py, r, g, b);
            drawHorizontalLine(cx - px, cx + px, cy - py, r, g, b);
            drawHorizontalLine(cx - py, cx + py, cy + px, r, g, b);
            drawHorizontalLine(cx - py, cx + py, cy - px, r, g, b);
        } else {
            setPixel(cx + px, cy + py, r, g, b);
            setPixel(cx - px, cy + py, r, g, b);
            setPixel(cx + px, cy - py, r, g, b);
            setPixel(cx - px, cy - py, r, g, b);
            setPixel(cx + py, cy + px, r, g, b);
            setPixel(cx - py, cy + px, r, g, b);
            setPixel(cx + py, cy - px, r, g, b);
            setPixel(cx - py, cy - px, r, g, b);
        }
    };

    while (x <= y) {
        plotSymmetric(x, y);
        if (d < 0) {
            d += 2 * x + 3;
        } else {
            d += 2 * (x - y) + 5;
            --y;
        }
        ++x;
    }
}

void BitmapWriter::drawRect(int x, int y, int w, int h,
                            uint8_t r, uint8_t g, uint8_t b, bool filled)
{
    if (filled) {
        for (int row = y; row < y + h; ++row) {
            drawHorizontalLine(x, x + w - 1, row, r, g, b);
        }
    } else {
        drawLine(x, y, x + w - 1, y, r, g, b);             // top
        drawLine(x, y + h - 1, x + w - 1, y + h - 1, r, g, b); // bottom
        drawLine(x, y, x, y + h - 1, r, g, b);             // left
        drawLine(x + w - 1, y, x + w - 1, y + h - 1, r, g, b); // right
    }
}

// ============================================================
// Text rendering (8×8 pixel font)
// ============================================================

void BitmapWriter::renderGlyph(const uint8_t glyph[8], int startX, int startY,
                               uint8_t r, uint8_t g, uint8_t b,
                               BitmapWriter& bmp)
{
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (0x80 >> col)) {
                bmp.setPixel(startX + col, startY + row, r, g, b);
            }
        }
    }
}

void BitmapWriter::drawText(int x, int y, const std::string& text,
                            uint8_t r, uint8_t g, uint8_t b)
{
    int cursorX = x;
    for (unsigned char ch : text) {
        if (ch >= 0x20 && ch <= 0x7E) {
            renderGlyph(FONT_8X8[ch - 0x20], cursorX, y, r, g, b, *this);
        }
        cursorX += 8; // fixed-width advance
    }
}

// ============================================================
// BMP file writer (platform-independent, little-endian)
// ============================================================

// Write a little-endian 16-bit value
static void writeLE16(std::ostream& os, uint16_t v)
{
    os.put(static_cast<char>(v & 0xFF));
    os.put(static_cast<char>((v >> 8) & 0xFF));
}

// Write a little-endian 32-bit value
static void writeLE32(std::ostream& os, uint32_t v)
{
    os.put(static_cast<char>(v & 0xFF));
    os.put(static_cast<char>((v >> 8) & 0xFF));
    os.put(static_cast<char>((v >> 16) & 0xFF));
    os.put(static_cast<char>((v >> 24) & 0xFF));
}

bool BitmapWriter::saveBMP(const std::string& filename, std::string& err) const
{
    std::ofstream ofs(filename, std::ios::binary);
    if (!ofs) {
        err = "Cannot open file: " + filename;
        return false;
    }

    // Row size must be padded to a multiple of 4 bytes
    // Guard against overflow for very large images
    if (width_ > 100000 || height_ > 100000) {
        err = "Image dimensions too large for BMP format";
        return false;
    }
    int rowBytes = width_ * 3;
    int paddingBytes = (4 - (rowBytes % 4)) % 4;
    int paddedRowSize = rowBytes + paddingBytes;

    uint32_t pixelDataSize = static_cast<uint32_t>(paddedRowSize) * height_;
    uint32_t fileSize = 14 + 40 + pixelDataSize;  // header + DIB + pixels

    // ---- BMP File Header (14 bytes) ----
    ofs.put('B'); ofs.put('M');           // Signature
    writeLE32(ofs, fileSize);             // File size
    writeLE16(ofs, 0);                    // Reserved1
    writeLE16(ofs, 0);                    // Reserved2
    writeLE32(ofs, 14 + 40);             // Pixel data offset

    // ---- DIB Header (BITMAPINFOHEADER, 40 bytes) ----
    writeLE32(ofs, 40);                   // DIB header size
    writeLE32(ofs, static_cast<uint32_t>(width_));  // Width
    writeLE32(ofs, static_cast<uint32_t>(height_)); // Height (positive = bottom-up)
    writeLE16(ofs, 1);                    // Color planes
    writeLE16(ofs, 24);                   // Bits per pixel
    writeLE32(ofs, 0);                    // Compression (BI_RGB = none)
    writeLE32(ofs, pixelDataSize);        // Image size
    writeLE32(ofs, 2835);                 // H resolution (72 DPI ≈ 2835 px/m)
    writeLE32(ofs, 2835);                 // V resolution
    writeLE32(ofs, 0);                    // Colors in palette
    writeLE32(ofs, 0);                    // Important colors

    // ---- Pixel Data (bottom-up, BGR) ----
    const uint8_t pad[3] = {0, 0, 0};
    for (int y = height_ - 1; y >= 0; --y) {
        for (int x = 0; x < width_; ++x) {
            size_t idx = (static_cast<size_t>(y) * width_ + x) * 3;
            // BMP stores pixels as BGR
            ofs.put(static_cast<char>(pixels_[idx + 2])); // B
            ofs.put(static_cast<char>(pixels_[idx + 1])); // G
            ofs.put(static_cast<char>(pixels_[idx]));     // R
        }
        if (paddingBytes > 0) {
            ofs.write(reinterpret_cast<const char*>(pad), paddingBytes);
        }
    }

    if (!ofs.good()) {
        err = "Failed to write BMP data to file";
        return false;
    }

    return true;
}
